#!/usr/bin/env python3
"""Generate poster macros exclusively from the paper SSOT JSON."""

import json
import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
STATS = REPO / "results/paper_stats.json"
MATRIX = REPO / "release/model_matrix.json"
OUT = REPO / "poster/poster_macros.tex"


def command(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main():
    stats = json.loads(STATS.read_text(encoding="utf-8"))["paper_v2"]
    matrix = json.loads(MATRIX.read_text(encoding="utf-8"))
    cells = stats["cells"]

    def score(condition, size, direction="arn-es"):
        return cells[f"{condition}|{size}|{direction}"]["chrfpp_mean"]

    vc_std = stats["comparisons"]["vc_minus_std_3.3B"]
    vc_morf = stats["comparisons"]["vc_minus_morf_3.3B"]
    boundaries = stats["segmentation"]["boundaries_train"]
    minimum_llm_gap = stats["margins"]["min_finetuned_over_llm"]

    macros = [
        "% Auto-generated by poster/generate_macros.py from results/paper_stats.json",
        "% Do not edit by hand.",
        command("TrainPairs", f"{stats['data']['train|arn']['sents']:,}"),
        command("NConditions", str(len(matrix["conditions"]))),
        command("NModels", str(len(matrix["conditions"]) * len(matrix["sizes"]) * len(matrix["directions"]))),
        command("MvcSixHundredArnEs", f"{score('Morfessor-VC', '600M'):.1f}"),
        command("MvcThreeBarnEs", f"{score('Morfessor-VC', '3.3B'):.1f}"),
        command("MorfThreeBarnEs", f"{score('Morfessor', '3.3B'):.1f}"),
        command("StdBpeThreeBarnEs", f"{score('Standard BPE', '3.3B'):.1f}"),
        command("StdBpeSixHundredArnEs", f"{score('Standard BPE', '600M'):.1f}"),
        command("VcStdThreeDelta", f"{vc_std['diff']:.2f}"),
        command("VcStdThreePval", f"{vc_std['p']:.3f}"),
        command("VcOverMorfDelta", f"{vc_morf['diff']:.2f}"),
        command("VcOverMorfPval", f"{vc_morf['p']:.4f}"),
        command("LlmGap", f"{math.floor(minimum_llm_gap)}+"),
        command("VcBoundariesRemoved", f"{boundaries['removed']:,}"),
        command("VcBoundariesTotal", f"{boundaries['morfessor']:,}"),
        command("VcBoundariesRemovedPct", f"{boundaries['removed_pct']:.1f}\\%"),
    ]
    OUT.write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
